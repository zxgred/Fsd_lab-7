-- University API Access Management System - database for XAMPP (MySQL / MariaDB)
-- The server also creates all of this automatically on first start.
-- Manual option: phpMyAdmin > Import tab > choose this file > Go
CREATE DATABASE IF NOT EXISTS university_api_db CHARACTER SET utf8mb4;
USE university_api_db;

-- 1. Students
CREATE TABLE IF NOT EXISTS students (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  roll_no VARCHAR(20) NOT NULL UNIQUE,
  full_name VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  department VARCHAR(100) NOT NULL,
  semester TINYINT UNSIGNED NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
) ENGINE=InnoDB;

-- 2. Teachers
CREATE TABLE IF NOT EXISTS teachers (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  employee_no VARCHAR(20) NOT NULL UNIQUE,
  full_name VARCHAR(100) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  department VARCHAR(100) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id)
) ENGINE=InnoDB;

-- 3. Courses
CREATE TABLE IF NOT EXISTS courses (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  code VARCHAR(20) NOT NULL UNIQUE,
  title VARCHAR(150) NOT NULL,
  credit_hours TINYINT UNSIGNED NOT NULL,
  PRIMARY KEY (id)
) ENGINE=InnoDB;

-- 4. Academic marks (one row per student per course)
CREATE TABLE IF NOT EXISTS marks (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  student_id INT UNSIGNED NOT NULL,
  course_id INT UNSIGNED NOT NULL,
  teacher_id INT UNSIGNED NOT NULL,
  assignment DECIMAL(5,2) NOT NULL,   -- out of 20
  midterm DECIMAL(5,2) NOT NULL,      -- out of 30
  final_exam DECIMAL(5,2) NOT NULL,   -- out of 50
  PRIMARY KEY (id),
  UNIQUE KEY one_mark_per_course (student_id, course_id),
  FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE,
  FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE CASCADE,
  FOREIGN KEY (teacher_id) REFERENCES teachers(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 5. API keys (generated by the admin; only a SHA-256 hash of the key is stored)
CREATE TABLE IF NOT EXISTS api_keys (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT,
  key_hash CHAR(64) NOT NULL UNIQUE,
  key_prefix VARCHAR(12) NOT NULL,
  role ENUM('student','teacher') NOT NULL,
  student_id INT UNSIGNED NULL,
  teacher_id INT UNSIGNED NULL,
  request_limit INT UNSIGNED NOT NULL DEFAULT 50,
  requests_used INT UNSIGNED NOT NULL DEFAULT 0,
  status ENUM('active','revoked') NOT NULL DEFAULT 'active',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_used_at DATETIME NULL,
  revoked_at DATETIME NULL,
  PRIMARY KEY (id),
  FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE CASCADE,
  FOREIGN KEY (teacher_id) REFERENCES teachers(id) ON DELETE CASCADE
) ENGINE=InnoDB;

-- 6. API usage log (one row for every request made with a valid key)
CREATE TABLE IF NOT EXISTS api_usage_log (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  api_key_id INT UNSIGNED NOT NULL,
  method VARCHAR(10) NOT NULL,
  endpoint VARCHAR(255) NOT NULL,
  status_code SMALLINT UNSIGNED NOT NULL,
  called_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  FOREIGN KEY (api_key_id) REFERENCES api_keys(id) ON DELETE CASCADE
) ENGINE=InnoDB;

